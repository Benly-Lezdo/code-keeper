// Simple JavaScript length example

// Command: get total characters in a string using .length
const word = "JavaScript";
console.log("String length:", word.length);

// Command: get total items in an array using .length
const letters = ["a", "b", "c", "d"];
console.log("Array length:", letters.length);

// Command: get total objects in an array using .length
const users = [
  { id: 1, name: "Asha", role: "Admin" },
  { id: 2, name: "Ravi", role: "Editor" },
  { id: 3, name: "Meera", role: "Viewer" },
];

console.log("Total objects in users array:", users.length);
